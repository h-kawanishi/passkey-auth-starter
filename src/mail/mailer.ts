/**
 * メール送信の窓口。送信事業者との接続は本実装の範囲外（§2）なので、
 * 利用者が自分の事業者向けにこの型を実装して差し替えられるようにしておく（buildApp の mailer に渡す）。
 *
 * S11: メールはパスワード再設定（アカウントの回復）にだけ使い、ログインの要素（認証）には使わない。
 * メールの受信箱は乗っ取られうるし、届くまでの経路も暗号化されているとは限らないので、
 * 「メールに届いたコードを入れたらログインできる」という作りは、本人確認として弱すぎるため。
 *
 * 実装する人へ: send が投げた例外の文やログに、本文（再設定リンク＝トークンの生値）を含めないこと（S12）。
 */
export interface Mailer {
  send(to: string, subject: string, body: string): Promise<void>;
}
